function englishPossessive(noun) {
  return noun.endsWith("s") ? `${noun}'` : `${noun}'s`;
}

function englishIndefinite(word) {
  if (/^(?:usual|user|university|united|euro|one)/i.test(word)) return "a";
  return /^(?:[aeiou]|honest|hour|heir)/i.test(word) ? "an" : "a";
}

function feminineAccusativeArticle(word) {
  return /^(?:[αεηιουωάέήίόύώϊΐϋΰκπτξψ]|μπ|ντ|γκ|τσ|τζ)/i.test(word) ? "την" : "τη";
}

function englishExampleAdjective(card) {
  return card.exampleEnglish || card.english;
}

function englishGenitive(card, noun, isDefinite, isPlural = false) {
  const adjective = noun.exampleEnglish || englishExampleAdjective(card);
  if (card.englishGenitiveStyle === "of") {
    const article = isPlural || isDefinite ? "the" : englishIndefinite(adjective);
    const nounForm = noun.english[isPlural ? 1 : 0];
    return `This is the ${card.examplePossession[1]} of ${article} ${adjective} ${nounForm}.`;
  }

  if (isPlural) {
    return `This is the ${adjective} ${englishPossessive(noun.english[1])} ${card.examplePossession[1]}.`;
  }

  const article = isDefinite ? "the" : englishIndefinite(adjective);
  return `This is ${article} ${adjective} ${noun.english[0]}'s ${card.examplePossession[1]}.`;
}

